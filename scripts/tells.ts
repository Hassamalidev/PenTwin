/**
 * The tell audit: renders the same text in every preset, and with no variation at all,
 * in the demo handwriting and in the test letters, and measures each page for the signs
 * that give machine writing away. Prints a table and writes docs/realism-audit.md.
 *
 *   pnpm tells          print and write the report
 *   pnpm tells --check  print only; exit 1 if a preset fails a tell
 */
import { writeFileSync } from 'node:fs';
import {
  auditTells,
  buildGlyphBank,
  INKS,
  judgeTells,
  NO_JITTER,
  presetOptions,
  PRESETS,
  renderText,
  TELL_LIMITS,
  type GlyphBank,
  type PresetName,
  type RenderOptions,
  type TellName,
} from '../packages/engine/src/index';
import { loadGlyphBank } from '../packages/engine/src/node/index';
import { buildDemoHand } from './demo-hand';

const TEXT =
  'It is quite likely that the first trial will be discarded, since the timer started late ' +
  'and the liquid had not settled. In the second and third trials the readings were within ' +
  'a minute of each other, which is fine for this initial test. Write it in the notebook, ' +
  'tick it off the list and fix a time to finish the remaining items with the instructor.';
const X_HEIGHT = 3;

const hand = buildDemoHand();
const banks: Record<string, GlyphBank> = {
  'demo hand': buildGlyphBank(hand.metadata, (file) => hand.files[file]!),
  'test letters': loadGlyphBank('tests/fixtures/glyphs/sample-user').bank,
};

const cases: [string, Omit<RenderOptions, 'seed'>][] = [
  // A mechanical page: what a handwriting font gives.
  ['no variation', { jitter: NO_JITTER, paper: { kind: 'plain' } }],
  // The normal style as it was before the 2026-10 release review: no pen model, dots
  // where the letter puts them, words parallel to their line, no joins.
  [
    'normal, before review',
    {
      ...presetOptions('normal'),
      jitter: { ...PRESETS.normal, dotDrift: 0, wordTilt: 0, joins: 0 },
      ink: { ...INKS['ballpoint-blue'], pen: undefined },
    },
  ],
  ...(Object.keys(PRESETS) as PresetName[]).map((name): [string, Omit<RenderOptions, 'seed'>] => [
    name,
    presetOptions(name),
  ]),
];

const names = Object.keys(TELL_LIMITS) as TellName[];
const rows: string[] = [];
let failed = 0;
for (const [bankName, bank] of Object.entries(banks)) {
  for (const [caseName, options] of cases) {
    const { pages } = renderText(TEXT, bank, {
      seed: 'tells',
      pageSize: 'A4',
      xHeight: X_HEIGHT,
      ...options,
    });
    const report = auditTells(pages, X_HEIGHT);
    const verdicts = judgeTells(report);
    if (!['no variation', 'normal, before review'].includes(caseName))
      failed += verdicts.filter((v) => !v.pass).length;
    const cells = verdicts.map((v) =>
      v.value === undefined ? 'n/a' : `${v.value.toFixed(3)} ${v.pass ? 'pass' : '**FAIL**'}`,
    );
    rows.push(`| ${bankName} | ${caseName} | ${cells.join(' | ')} |`);
  }
}

const header =
  `| Hand | Style | ${names.map((n) => TELL_LIMITS[n].label).join(' | ')} |\n` +
  `| --- | --- | ${names.map(() => '---').join(' | ')} |\n` +
  `| | limit | ${names
    .map(
      (n) =>
        `${TELL_LIMITS[n].kind === 'max' ? '<=' : '>='} ${TELL_LIMITS[n].value} ${TELL_LIMITS[n].unit}`,
    )
    .join(' | ')} |\n`;
const table = header + rows.join('\n') + '\n';
console.log(table);

if (!process.argv.includes('--check')) {
  writeFileSync(
    'docs/realism-audit.md',
    `# Realism audit (tells)

Generated by \`pnpm tells\` (\`scripts/tells.ts\`, measures in \`packages/engine/src/tells.ts\`).
The same paragraph is written at a 3 mm x-height in every style, and with no variation
at all, in two hands: the demo handwriting the site uses and the plain test letters.

## Read this first

- **The limits are this project's own judgement**, chosen so that a page with no
  variation fails and a neat but human page passes. They are **not measured from real
  people's writing.** Passing them is not evidence for the blind-test gate (1.11).
- Both hands are synthetic. Pages from a real user's photo carry the user's own pen in
  their outlines, so "Pen of one weight" is not measured for them.
- The audit is a regression guard: a change that makes any style fail a tell needs a
  reason, or it is reverted. \`pnpm tells --check\` runs it without writing this file.

## What each tell measures

| Tell | Measure |
| --- | --- |
| Identical letters | Share of letters whose outline exactly matches an earlier copy of the same letter. |
| Ruler-straight lines | Spread of the bottoms of small letters around a straight line fitted to each line, in x-heights. |
| Pen of one weight | Relative change of the pen's width along each stroke, plus the spread of widths between strokes. |
| Dots placed by template | Spread of the i-dot's offset from the centre of its stem, in x-heights. |
| Words all parallel | Spread of the tilt of each word against its own line, in degrees. |

## Results

${table}
"No variation" is expected to fail: it is the mechanical page the audit exists to catch.
"Normal, before review" is the normal style as it was before the release review
(\`docs/release-review.md\`) added the pen model, dot drift, word tilt and joins; it is kept for
comparison and is not required to pass.

The demo hand passes "ruler-straight lines" and "dots placed by template" even with no
variation, because its four hand-drawn variants of each letter already differ in height
and in where the dot sits. That is a property of the hand, not of the engine.

The word-tilt limit is about three times what a page with no variation measures in the
plain test letters (0.15 degrees). The other limits are set by eye against the samples.
`,
  );
  console.log('docs/realism-audit.md');
}
if (failed > 0) {
  console.error(`${failed} tell(s) failed in a preset.`);
  process.exit(1);
}
